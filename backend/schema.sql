-- Skema sistem piutang furnitur untuk Supabase / PostgreSQL.
CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    phone TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    credit_limit NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (credit_limit >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no TEXT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    invoice_date DATE NOT NULL,
    due_date DATE NOT NULL,
    total_amount NUMERIC(14, 2) NOT NULL CHECK (total_amount > 0),
    status TEXT NOT NULL DEFAULT 'Unpaid' CHECK (status IN ('Unpaid', 'Partial', 'Paid')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE invoice_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    product_name TEXT NOT NULL CHECK (length(trim(product_name)) > 0),
    qty INTEGER NOT NULL CHECK (qty > 0),
    unit_price NUMERIC(14, 2) NOT NULL CHECK (unit_price >= 0),
    subtotal NUMERIC(14, 2) NOT NULL CHECK (subtotal > 0)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    payment_date DATE NOT NULL,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    method TEXT NOT NULL CHECK (method IN ('Cash', 'Transfer')),
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX invoices_customer_id_idx ON invoices(customer_id);
CREATE INDEX invoice_items_invoice_id_idx ON invoice_items(invoice_id);
CREATE INDEX payments_invoice_id_idx ON payments(invoice_id);

CREATE VIEW v_aging_schedule AS
WITH payment_totals AS (
    SELECT invoice_id, SUM(amount) AS paid_amount
    FROM payments
    GROUP BY invoice_id
),
invoice_balances AS (
    SELECT
        i.id AS invoice_id,
        i.invoice_no,
        i.customer_id,
        c.name AS customer_name,
        i.invoice_date,
        i.due_date,
        i.total_amount,
        i.total_amount - COALESCE(p.paid_amount, 0) AS outstanding,
        CURRENT_DATE - i.due_date AS days_overdue
    FROM invoices i
    JOIN customers c ON c.id = i.customer_id
    LEFT JOIN payment_totals p ON p.invoice_id = i.id
)
SELECT
    invoice_id,
    invoice_no,
    customer_id,
    customer_name,
    invoice_date,
    due_date,
    total_amount,
    outstanding,
    days_overdue,
    CASE
        WHEN days_overdue <= 0 THEN 'Belum Jatuh Tempo'
        WHEN days_overdue <= 30 THEN '1-30 Hari'
        WHEN days_overdue <= 60 THEN '31-60 Hari'
        WHEN days_overdue <= 90 THEN '61-90 Hari'
        ELSE '>90 Hari'
    END AS bucket
FROM invoice_balances
WHERE outstanding > 0;

